-- ============================================================
-- مشروع SQL المستوى الثاني - مدرسة التميز للتعليم الثانوي
-- ============================================================

USE altamayoz_school;

-- ============================================================
-- أولاً: إنشاء البيانات الجديدة
-- ============================================================

-- حذف الجداول إذا كانت موجودة مسبقاً لتجنب الأخطاء
DROP TABLE IF EXISTS top_students;
DROP TABLE IF EXISTS failed_students;

-- ============================================================
-- المتطلب 1: إنشاء جدول الطلاب المتفوقين (معدل أعلى من 90)
-- ============================================================
CREATE TABLE top_students AS
SELECT * FROM students
WHERE gpa > 90;

-- عرض جدول المتفوقين للتأكد
SELECT * FROM top_students;

-- ============================================================
-- المتطلب 2: إنشاء جدول الطلاب الغير مجتازين (معدل أقل من 60)
-- ============================================================
CREATE TABLE failed_students AS
SELECT * FROM students
WHERE gpa < 60;

-- عرض جدول الغير مجتازين للتأكد
SELECT * FROM failed_students;

-- ============================================================
-- المتطلب 3: عرض أسماء الطلاب التي تبدأ بحرف A
-- (استخدام LIKE)
-- ============================================================
SELECT student_name
FROM students
WHERE student_name LIKE 'A%';

-- ============================================================
-- المتطلب 4: عرض أسماء الطلاب التي تحتوي على أربع خانات
-- (استخدام LIKE مع 4 شرطات سفلية)
-- ============================================================
SELECT student_name
FROM students
WHERE student_name LIKE '____';

-- ============================================================
-- المتطلب 5: تطبيق Aggregate Functions على المعدل التراكمي
-- (AVG, MAX, MIN مع تسمية واضحة AS)
-- ============================================================
SELECT
    AVG(gpa) AS 'متوسط المعدل التراكمي',
    MAX(gpa) AS 'أعلى معدل تراكمي',
    MIN(gpa) AS 'أدنى معدل تراكمي',
    SUM(gpa) AS 'مجموع المعدلات',
    COUNT(id) AS 'عدد الطلاب'
FROM students;

-- ============================================================
-- المتطلب 6: عرض الطلاب المتفوقين في المستوى السادس بمعدل 100
-- (استخدام AND)
-- ============================================================
SELECT student_name, grade_level, gpa
FROM students
WHERE grade_level = 6
AND gpa = 100;

-- ============================================================
-- المتطلب 7: عرض طلاب المستوى الأول بعمر بين 15 و16 سنة
-- (استخدام BETWEEN وحساب العمر من تاريخ الميلاد)
-- ============================================================
SELECT
    student_name,
    birth_date,
    TIMESTAMPDIFF(YEAR, birth_date, CURDATE()) AS 'العمر',
    grade_level
FROM students
WHERE grade_level = 1
AND TIMESTAMPDIFF(YEAR, birth_date, CURDATE()) BETWEEN 15 AND 16;

-- ============================================================
-- المتطلب 8: عرض عدد الطلاب في المستوى الثاني
-- (استخدام COUNT)
-- ============================================================
SELECT COUNT(id) AS 'عدد طلاب المستوى الثاني'
FROM students
WHERE grade_level = 2;

-- ============================================================
-- المتطلب 9: استعراض مسارات الطلاب بدون تكرار
-- (استخدام DISTINCT)
-- ============================================================
SELECT DISTINCT track AS 'المسارات المتاحة'
FROM students;

-- ============================================================
-- المتطلب 10: عرض أسماء المواد بالأحرف الكبيرة
-- (استخدام UPPER - String Function)
-- ============================================================
SELECT UPPER(subject_name) AS 'اسم المادة'
FROM subjects;

-- ============================================================
-- المتطلب 11: المتوسط الحسابي للمعدل مقرباً لأقرب أصغر عدد
-- (استخدام FLOOR - Numeric Function)
-- ============================================================
SELECT FLOOR(AVG(gpa)) AS 'متوسط المعدل مقرباً للأسفل'
FROM students;

-- ============================================================
-- المتطلب 12: تبديل F إلى Female و M إلى Male
-- (استخدام REPLACE - String Function)
-- ============================================================
UPDATE students
SET gender = REPLACE(REPLACE(gender, 'F', 'Female'), 'M', 'Male');

-- عرض النتيجة بعد التعديل
SELECT student_name, gender FROM students;

-- ============================================================
-- المتطلب 13: زيادة معدل الطلاب الراسبين بخمس درجات
-- ============================================================
UPDATE students
SET gpa = gpa + 5
WHERE gpa < 60;

-- عرض النتيجة بعد التعديل
SELECT student_name, gpa AS 'المعدل بعد الزيادة'
FROM students
WHERE gpa < 65;

-- ============================================================
-- تطبيق إضافي: Aggregate Functions موسعة
-- ============================================================
SELECT
    grade_level AS 'المستوى',
    COUNT(id) AS 'عدد الطلاب',
    AVG(gpa) AS 'متوسط المعدل',
    MAX(gpa) AS 'أعلى معدل',
    MIN(gpa) AS 'أدنى معدل'
FROM students
GROUP BY grade_level
ORDER BY grade_level;

-- ============================================================
-- تطبيق إضافي: Numeric Functions
-- ============================================================
SELECT
    student_name AS 'اسم الطالب',
    gpa AS 'المعدل',
    ABS(gpa - 100)          AS 'الفرق عن 100 (ABS)',
    MOD(FLOOR(gpa), 10)     AS 'باقي القسمة على 10 (MOD)',
    DIV(FLOOR(gpa), 10)     AS 'ناتج القسمة الصحيح (DIV)',
    POW(2, 3)               AS 'مثال POW: 2 أس 3'
FROM students
LIMIT 5;

-- ============================================================
-- تطبيق إضافي: String Functions
-- ============================================================
SELECT
    student_name                        AS 'اسم الطالب',
    ASCII(student_name)                 AS 'ASCII لأول حرف',
    BIN(FLOOR(gpa))                     AS 'المعدل بالثنائي (BIN)',
    HEX(FLOOR(gpa))                     AS 'المعدل بالهيكساديسيمال (HEX)',
    CONCAT(student_name,' - ',track)    AS 'الاسم والمسار (CONCAT)'
FROM students
LIMIT 5;

-- ============================================================
-- تطبيق إضافي: Date & Time Functions
-- ============================================================
SELECT
    NOW()       AS 'التاريخ والوقت الآن (NOW)',
    CURDATE()   AS 'تاريخ اليوم (CURDATE)',
    CURTIME()   AS 'الوقت الحالي (CURTIME)';
